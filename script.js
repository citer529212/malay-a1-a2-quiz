function normalizeText(value) {
  return String(value || "")
    .trim()
    .toLowerCase()
    .normalize("NFKC")
    .replace(/[.,!?;:()[\]{}"'«»]/g, "")
    .replace(/\s+/g, " ");
}

function normalizeStudentPart(value) {
  return normalizeText(value).replace(/[^a-zа-яё\s-]/gi, "");
}

function getStudentKey(firstName, lastName) {
  return `${normalizeStudentPart(firstName)}::${normalizeStudentPart(lastName)}`;
}

function escapeHtml(value) {
  return String(value ?? "").replace(/[&<>"']/g, (char) => ({
    "&": "&amp;",
    "<": "&lt;",
    ">": "&gt;",
    '"': "&quot;",
    "'": "&#039;"
  }[char]));
}

function getBank(level = state.selectedLevel) {
  return QUESTION_BANKS[level] || QUESTION_BANKS.A1;
}

function getTotalPages() {
  return Math.ceil(getBank().length / CONFIG.questionsPerPage);
}

function getMaxScore(level = state.selectedLevel) {
  return getBank(level).reduce((sum, item) => sum + item.points, 0);
}

function getAnswer(questionId) {
  return state.answers[String(questionId)];
}

function isAnswered(question) {
  const value = getAnswer(question.id);
  return value !== undefined && String(value).trim() !== "";
}

function getVisibleQuestions() {
  const start = state.currentPage * CONFIG.questionsPerPage;
  return getBank().slice(start, start + CONFIG.questionsPerPage);
}

function safeJsonParse(value, fallback) {
  try {
    return JSON.parse(value) ?? fallback;
  } catch {
    return fallback;
  }
}

function loadAllProgress() {
  return safeJsonParse(localStorage.getItem(CONFIG.progressKey), {});
}

function saveAllProgress(progress) {
  localStorage.setItem(CONFIG.progressKey, JSON.stringify(progress));
}

function getDefaultStudentProgress() {
  return {
    highestUnlockedLevel: "A1",
    passedLevels: {},
    attempts: {},
    bestPercent: {},
    updatedAt: null
  };
}

function getStudentProgress(studentKey) {
  const all = loadAllProgress();
  return { ...getDefaultStudentProgress(), ...(all[studentKey] || {}) };
}

function saveStudentProgress(studentKey, progress) {
  const all = loadAllProgress();
  all[studentKey] = { ...progress, updatedAt: new Date().toISOString() };
  saveAllProgress(all);
}

function getLevelIndex(level) {
  return CONFIG.levels.indexOf(level);
}

function getNextLevel(level) {
  const nextIndex = getLevelIndex(level) + 1;
  return CONFIG.levels[nextIndex] || level;
}

function isLevelUnlocked(level, progress) {
  return getLevelIndex(level) <= getLevelIndex(progress.highestUnlockedLevel || "A1");
}

function getDraftKey(studentKey, level) {
  return `${CONFIG.draftPrefix}:${studentKey}:${level}`;
}

function readCurrentIdentity() {
  const firstName = els.firstNameInput.value.trim();
  const lastName = els.lastNameInput.value.trim();
  if (!firstName || !lastName || firstName.length < 2 || lastName.length < 2) return null;
  return {
    firstName,
    lastName,
    fullName: `${firstName} ${lastName}`,
    key: getStudentKey(firstName, lastName)
  };
}

function showStartError(message) {
  els.startError.textContent = message;
  els.startError.hidden = !message;
}

function renderLevelCards() {
  const identity = readCurrentIdentity();
  const progress = identity ? getStudentProgress(identity.key) : getDefaultStudentProgress();
  const highest = progress.highestUnlockedLevel || "A1";

  els.resetProgressBtn.hidden = !identity;
  els.progressHint.textContent = identity
    ? `Прогресс для: ${identity.fullName}. Максимально открыт: ${highest}.`
    : "Введите имя и фамилию, чтобы увидеть персональный прогресс.";

  if (!isLevelUnlocked(state.selectedLevel, progress)) {
    state.selectedLevel = highest;
  }

  els.levelGrid.innerHTML = CONFIG.levels.map((level) => {
    const unlocked = isLevelUnlocked(level, progress);
    const passed = Boolean(progress.passedLevels?.[level]);
    const attempts = progress.attempts?.[level] || 0;
    const best = progress.bestPercent?.[level];
    const statusClass = passed ? "passed" : unlocked ? "open" : "locked";
    const statusText = passed ? "Пройден" : unlocked ? "Открыт" : "Закрыт";
    const meta = unlocked
      ? `Попыток: ${attempts}. Лучший результат: ${best ?? "—"}%`
      : `Откроется после ${CONFIG.levels[getLevelIndex(level) - 1]}`;

    return `
      <button class="level-card ${statusClass}" type="button" role="radio"
        aria-checked="${state.selectedLevel === level}"
        data-level="${level}" ${unlocked ? "" : "disabled"}>
        <span class="level-name">${level}</span>
        <span class="level-status ${statusClass}">${statusText}</span>
        <span class="level-meta">${escapeHtml(meta)}</span>
      </button>`;
  }).join("");

  els.startBtn.disabled = !identity || !isLevelUnlocked(state.selectedLevel, progress);
}

function selectLevel(level) {
  const identity = readCurrentIdentity();
  const progress = identity ? getStudentProgress(identity.key) : getDefaultStudentProgress();
  if (!CONFIG.levels.includes(level) || !isLevelUnlocked(level, progress)) {
    showStartError("Этот уровень пока закрыт. Сначала пройдите предыдущий уровень на 70% или выше.");
    renderLevelCards();
    return;
  }
  state.selectedLevel = level;
  showStartError("");
  renderLevelCards();
}

function saveDraft() {
  if (!state.student || state.submitted) return;
  localStorage.setItem(getDraftKey(state.student.key, state.selectedLevel), JSON.stringify({
    student: state.student,
    selectedLevel: state.selectedLevel,
    currentPage: state.currentPage,
    answers: state.answers,
    startedAt: state.startedAt,
    remainingSeconds: state.remainingSeconds
  }));
}

function loadDraft(studentKey, level) {
  return safeJsonParse(localStorage.getItem(getDraftKey(studentKey, level)), null);
}

function clearDraft(studentKey = state.student?.key, level = state.selectedLevel) {
  if (!studentKey || !level) return;
  localStorage.removeItem(getDraftKey(studentKey, level));
}

function formatTime(totalSeconds) {
  const safe = Math.max(0, Number(totalSeconds) || 0);
  const minutes = Math.floor(safe / 60);
  const seconds = safe % 60;
  return `${String(minutes).padStart(2, "0")}:${String(seconds).padStart(2, "0")}`;
}

function updateTimer() {
  els.timer.textContent = formatTime(state.remainingSeconds);
  els.timer.classList.toggle("low", state.remainingSeconds <= 60);
}

function startTimer() {
  clearInterval(state.timerId);
  updateTimer();
  state.timerId = window.setInterval(() => {
    state.remainingSeconds -= 1;
    updateTimer();
    saveDraft();
    if (state.remainingSeconds <= 0) {
      finishQuiz("timeout");
    }
  }, 1000);
}

function renderQuiz() {
  const bank = getBank();
  const totalPages = getTotalPages();
  const answeredCount = bank.filter(isAnswered).length;
  const progressPercent = Math.round((answeredCount / bank.length) * 100);

  els.studentNameLabel.textContent = state.student.fullName;
  els.selectedLevelLabel.textContent = state.selectedLevel;
  els.progressBar.style.width = `${progressPercent}%`;
  els.progressText.textContent = `${answeredCount} из ${bank.length} отвечено`;
  els.pageLabel.textContent = `Страница ${state.currentPage + 1} из ${totalPages}`;
  els.prevBtn.disabled = state.currentPage === 0;
  els.nextBtn.hidden = state.currentPage === totalPages - 1;
  els.submitBtn.hidden = state.currentPage !== totalPages - 1;

  renderQuizMeta(bank, answeredCount, progressPercent);
  els.quizForm.innerHTML = getVisibleQuestions().map((question) => renderQuestion(question)).join("");
}

function renderQuizMeta(bank, answeredCount, progressPercent) {
  els.progressBar.style.width = `${progressPercent}%`;
  els.progressText.textContent = `${answeredCount} из ${bank.length} отвечено`;

  els.questionNav.innerHTML = bank.map((question, index) => {
    const page = Math.floor(index / CONFIG.questionsPerPage);
    const classes = ["nav-dot"];
    if (page === state.currentPage) classes.push("active");
    if (isAnswered(question)) classes.push("answered");
    return `<button class="${classes.join(" ")}" type="button" data-page="${page}" aria-label="Вопрос ${index + 1}">${index + 1}</button>`;
  }).join("");
}

function renderQuestion(question) {
  const saved = getAnswer(question.id);
  const body = question.type === "mcq" ? renderMcq(question, saved) : renderText(question, saved);
  return `
    <article class="question-card" data-question-id="${question.id}">
      <div class="question-head">
        <div class="question-title">${question.id}. ${escapeHtml(question.q)}</div>
        <div class="points-pill">${question.points} ${question.points === 1 ? "балл" : "балла"}</div>
      </div>
      ${body}
    </article>`;
}

function renderMcq(question, saved) {
  return `<div class="options">${question.options.map((option, index) => `
    <label class="option-label">
      <input type="radio" name="q-${question.id}" value="${index}" ${String(saved) === String(index) ? "checked" : ""} />
      <span>${escapeHtml(option)}</span>
    </label>`).join("")}</div>`;
}

function renderText(question, saved) {
  return `<input class="text-answer" type="text" name="q-${question.id}" value="${escapeHtml(saved || "")}" autocomplete="off" inputmode="text" />`;
}

function collectAnswerFromEvent(event) {
  const input = event.target;
  if (!(input instanceof HTMLInputElement) || !input.name.startsWith("q-")) return;
  const questionId = input.name.replace("q-", "");
  if (input.type === "radio") {
    if (input.checked) state.answers[questionId] = input.value;
  } else {
    state.answers[questionId] = input.value;
  }
  saveDraft();

  // Keep focus in text input: update only meta UI, do not rebuild the form on each keystroke.
  const bank = getBank();
  const answeredCount = bank.filter(isAnswered).length;
  const progressPercent = Math.round((answeredCount / bank.length) * 100);
  renderQuizMeta(bank, answeredCount, progressPercent);
}

function goToPage(page) {
  const totalPages = getTotalPages();
  state.currentPage = Math.min(Math.max(0, page), totalPages - 1);
  saveDraft();
  renderQuiz();
  window.scrollTo({ top: 0, behavior: "smooth" });
}

function isCorrect(question) {
  const answer = getAnswer(question.id);
  if (question.type === "mcq") return Number(answer) === question.correct;
  return normalizeText(answer) === normalizeText(question.correct);
}

function calculateResult() {
  const bank = getBank();
  const maxScore = getMaxScore();
  const sectionStats = {};
  let score = 0;
  let correctCount = 0;

  for (const question of bank) {
    const section = String(question.section);
    sectionStats[section] ||= { score: 0, max: 0 };
    sectionStats[section].max += question.points;
    if (isCorrect(question)) {
      score += question.points;
      correctCount += 1;
      sectionStats[section].score += question.points;
    }
  }

  const incorrectCount = bank.length - correctCount;
  const percent = Math.round((score / maxScore) * 100);
  const passed = percent >= CONFIG.passingPercent;
  return { score, maxScore, correctCount, incorrectCount, percent, passed, sectionStats };
}

function getLevelLabelByPercent(percent) {
  if (percent >= 90) return "excellent";
  if (percent >= 70) return "passed";
  if (percent >= 50) return "basic";
  return "needs_practice";
}

function getHighestUnlockedAfterResult(progress, selectedLevel, passed) {
  if (!passed) return progress.highestUnlockedLevel || "A1";
  const currentHighestIndex = getLevelIndex(progress.highestUnlockedLevel || "A1");
  const nextIndex = Math.min(getLevelIndex(selectedLevel) + 1, CONFIG.levels.length - 1);
  return CONFIG.levels[Math.max(currentHighestIndex, nextIndex)];
}

function updateProgressAfterAttempt(result) {
  const progress = getStudentProgress(state.student.key);
  const attempts = { ...(progress.attempts || {}) };
  const bestPercent = { ...(progress.bestPercent || {}) };
  const passedLevels = { ...(progress.passedLevels || {}) };

  attempts[state.selectedLevel] = (attempts[state.selectedLevel] || 0) + 1;
  bestPercent[state.selectedLevel] = Math.max(bestPercent[state.selectedLevel] || 0, result.percent);
  if (result.passed) passedLevels[state.selectedLevel] = true;

  const updated = {
    ...progress,
    attempts,
    bestPercent,
    passedLevels,
    highestUnlockedLevel: getHighestUnlockedAfterResult(progress, state.selectedLevel, result.passed)
  };
  saveStudentProgress(state.student.key, updated);
  state.attemptNumberForLevel = attempts[state.selectedLevel];
  return updated;
}

function buildAnswersPayload() {
  return getBank().map((question) => ({
    id: question.id,
    selectedLevel: state.selectedLevel,
    section: question.section,
    type: question.type,
    question: question.q,
    answer: getAnswer(question.id) ?? "",
    correctAnswer: question.type === "mcq" ? question.options[question.correct] : question.correct,
    isCorrect: isCorrect(question),
    points: isCorrect(question) ? question.points : 0,
    maxPoints: question.points
  }));
}

function buildSubmissionPayload(result, finishReason, updatedProgress) {
  const timeUsedSeconds = CONFIG.secondsTotal - Math.max(0, state.remainingSeconds);
  const payload = {
    studentFullName: state.student.fullName,
    studentFirstName: state.student.firstName,
    studentLastName: state.student.lastName,
    score: result.score,
    maxScore: result.maxScore,
    level: getLevelLabelByPercent(result.percent),
    correctCount: result.correctCount,
    incorrectCount: result.incorrectCount,
    timeUsed: formatTime(timeUsedSeconds),
    timeUsedSeconds,
    finishReason,
    selectedLevel: state.selectedLevel,
    passed: result.passed,
    percent: result.percent,
    highestUnlockedLevel: updatedProgress.highestUnlockedLevel,
    attemptNumberForLevel: state.attemptNumberForLevel,
    startedAt: state.startedAt,
    finishedAt: state.finishedAt,
    answers: JSON.stringify(buildAnswersPayload())
  };

  for (const section of [1, 2, 3, 4]) {
    payload[`section${section}Score`] = result.sectionStats[String(section)]?.score || 0;
    payload[`section${section}Max`] = result.sectionStats[String(section)]?.max || 0;
  }

  return payload;
}

async function submitToSheets(payload) {
  const formData = new FormData();
  Object.entries(payload).forEach(([key, value]) => formData.append(key, String(value)));
  await fetch(CONFIG.appsScriptUrl, { method: "POST", mode: "no-cors", body: formData });
}

function renderResults(result, updatedProgress) {
  const bannerClass = result.passed ? "pass" : "fail";
  const bannerText = result.passed
    ? `Уровень ${state.selectedLevel} пройден. Открыт уровень ${updatedProgress.highestUnlockedLevel}.`
    : `Уровень ${state.selectedLevel} не пройден. Нужно минимум ${CONFIG.passingPercent}%. Можно попробовать ещё раз.`;

  els.resultSummary.innerHTML = `
    <div class="pass-banner ${bannerClass}">${escapeHtml(bannerText)}</div>
    <div class="metric"><span>Балл</span><strong>${result.score}/${result.maxScore}</strong></div>
    <div class="metric"><span>Процент</span><strong>${result.percent}%</strong></div>
    <div class="metric"><span>Верно</span><strong>${result.correctCount}</strong></div>
    <div class="metric"><span>Попытка</span><strong>${state.attemptNumberForLevel}</strong></div>`;

  els.sectionBreakdown.innerHTML = [1, 2, 3, 4].map((section) => {
    const stats = result.sectionStats[String(section)] || { score: 0, max: 0 };
    return `<div class="section-row"><span>Секция ${section}</span><strong>${stats.score}/${stats.max}</strong></div>`;
  }).join("");

  els.answerReview.innerHTML = getBank().map((question) => {
    const correct = isCorrect(question);
    const answer = getAnswer(question.id) ?? "—";
    const correctAnswer = question.type === "mcq" ? question.options[question.correct] : question.correct;
    return `
      <div class="review-item ${correct ? "correct" : "incorrect"}">
        <strong>${question.id}. ${escapeHtml(question.q)}</strong>
        <div>Ваш ответ: ${escapeHtml(answer)}</div>
        <div>Правильный ответ: ${escapeHtml(correctAnswer)}</div>
      </div>`;
  }).join("");
}

async function finishQuiz(finishReason) {
  if (state.submitted) return;
  state.submitted = true;
  clearInterval(state.timerId);
  state.finishedAt = new Date().toISOString();

  const result = calculateResult();
  const updatedProgress = updateProgressAfterAttempt(result);
  const payload = buildSubmissionPayload(result, finishReason, updatedProgress);

  renderResults(result, updatedProgress);
  els.saveStatus.textContent = "Сохраняем результат…";
  els.saveStatus.className = "save-status";
  els.resultModal.hidden = false;
  clearDraft();

  try {
    await submitToSheets(payload);
    els.saveStatus.textContent = "Результат отправлен в Google Sheets.";
    els.saveStatus.classList.add("ok");
  } catch (error) {
    console.error(error);
    els.saveStatus.textContent = "Результат сохранён локально, но отправка в Sheets не удалась.";
    els.saveStatus.classList.add("fail");
  }
}

function beginQuiz(student, level) {
  const progress = getStudentProgress(student.key);
  if (!isLevelUnlocked(level, progress)) {
    showStartError("Уровень закрыт. Пройдите предыдущий уровень на 70% или выше.");
    renderLevelCards();
    return;
  }

  const draft = loadDraft(student.key, level);
  state.student = student;
  state.selectedLevel = level;
  state.currentPage = draft?.currentPage || 0;
  state.answers = draft?.answers || {};
  state.startedAt = draft?.startedAt || new Date().toISOString();
  state.remainingSeconds = Math.min(CONFIG.secondsTotal, Math.max(0, draft?.remainingSeconds ?? CONFIG.secondsTotal));
  state.submitted = false;
  state.attemptNumberForLevel = (progress.attempts?.[level] || 0) + 1;

  els.startScreen.hidden = true;
  els.quizScreen.hidden = false;
  renderQuiz();
  startTimer();
}

function resetToStart() {
  clearInterval(state.timerId);
  state.currentPage = 0;
  state.answers = {};
  state.startedAt = null;
  state.finishedAt = null;
  state.remainingSeconds = CONFIG.secondsTotal;
  state.submitted = false;
  els.resultModal.hidden = true;
  els.quizScreen.hidden = true;
  els.startScreen.hidden = false;
  renderLevelCards();
}

function handleSubmitAttempt() {
  const unanswered = getBank().filter((question) => !isAnswered(question)).length;
  const message = unanswered
    ? `Есть ${unanswered} вопрос(ов) без ответа. Завершить тест?`
    : "Завершить тест и отправить результат?";
  if (window.confirm(message)) finishQuiz("manual");
}

function bindEvents() {
  els.firstNameInput.addEventListener("input", renderLevelCards);
  els.lastNameInput.addEventListener("input", renderLevelCards);

  els.levelGrid.addEventListener("click", (event) => {
    const button = event.target.closest("[data-level]");
    if (!button) return;
    selectLevel(button.dataset.level);
  });

  els.studentForm.addEventListener("submit", (event) => {
    event.preventDefault();
    const student = readCurrentIdentity();
    if (!student) {
      showStartError("Введите имя и фамилию минимум по 2 символа.");
      return;
    }
    beginQuiz(student, state.selectedLevel);
  });

  els.resetProgressBtn.addEventListener("click", () => {
    const student = readCurrentIdentity();
    if (!student) return;
    if (!window.confirm(`Сбросить прогресс и черновики для ${student.fullName}?`)) return;
    const all = loadAllProgress();
    delete all[student.key];
    saveAllProgress(all);
    CONFIG.levels.forEach((level) => clearDraft(student.key, level));
    state.selectedLevel = "A1";
    renderLevelCards();
  });

  els.quizForm.addEventListener("input", collectAnswerFromEvent);
  els.quizForm.addEventListener("change", collectAnswerFromEvent);

  els.questionNav.addEventListener("click", (event) => {
    const button = event.target.closest("[data-page]");
    if (button) goToPage(Number(button.dataset.page));
  });

  els.prevBtn.addEventListener("click", () => goToPage(state.currentPage - 1));
  els.nextBtn.addEventListener("click", () => goToPage(state.currentPage + 1));
  els.submitBtn.addEventListener("click", handleSubmitAttempt);

  els.clearDraftBtn.addEventListener("click", () => {
    if (!window.confirm("Очистить ответы текущего уровня и начать страницу заново?")) return;
    state.answers = {};
    state.currentPage = 0;
    state.remainingSeconds = CONFIG.secondsTotal;
    clearDraft();
    renderQuiz();
    updateTimer();
  });

  els.closeModalBtn.addEventListener("click", resetToStart);
  els.restartBtn.addEventListener("click", resetToStart);

  window.addEventListener("beforeunload", (event) => {
    if (state.student && !state.submitted && !els.quizScreen.hidden) {
      saveDraft();
      event.preventDefault();
      event.returnValue = "";
    }
  });
}

function validateQuestionBanks() {
  for (const level of CONFIG.levels) {
    const bank = QUESTION_BANKS[level];
    if (!Array.isArray(bank) || bank.length !== 30) {
      throw new Error(`Question bank ${level} must contain exactly 30 questions.`);
    }
  }
}

function init() {
  validateQuestionBanks();
  bindEvents();
  renderLevelCards();
}

init();
